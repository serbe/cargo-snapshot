use super::{Metadata, Renderer};
use anyhow::Result;
use std::io::Write;

pub(crate) struct MarkdownRenderer;

impl MarkdownRenderer {
    pub(crate) fn new() -> Self {
        Self
    }
}

impl Renderer for MarkdownRenderer {
    fn render_header(&self, out: &mut dyn Write) -> Result<()> {
        writeln!(out, "# CARGO SNAPSHOT")?;
        writeln!(out, "*Generated by cargo-snapshot*\n")?;
        writeln!(out, "---\n")?;
        Ok(())
    }

    fn render_metadata(&self, out: &mut dyn Write, metadata: &Metadata<'_>) -> Result<()> {
        writeln!(out, "## Metadata\n")?;

        if let Some(pkg) = metadata.package {
            writeln!(out, "**Package:** `{}`", pkg.name)?;
            if let Some(v) = &pkg.version {
                writeln!(out, "- **Version:** `{v}`")?;
            }
            if let Some(e) = &pkg.edition {
                writeln!(out, "- **Edition:** `{e}`")?;
            }
            if let Some(l) = &pkg.license {
                writeln!(out, "- **License:** `{l}`")?;
            }
            if let Some(d) = &pkg.description {
                writeln!(out, "- **Description:** {d}")?;
            }
        }

        if let Some(ws) = metadata.workspace {
            if let Some(name) = &metadata.workspace_name {
                writeln!(out, "**Workspace:** `{name}`")?;
            }
            writeln!(out, "- **Type:** workspace")?;

            if !ws.members.is_empty() {
                writeln!(out, "- **Members:** `{}`", ws.members.join("`, `"))?;
            }
            if let Some(r) = &ws.resolver {
                writeln!(out, "- **Resolver:** `{r}`")?;
            }
            if let Some(pkg) = &ws.package {
                if let Some(v) = &pkg.version {
                    writeln!(out, "- **Version:** `{v}`")?;
                }
                if let Some(e) = &pkg.edition {
                    writeln!(out, "- **Edition:** `{e}`")?;
                }
                if let Some(l) = &pkg.license {
                    writeln!(out, "- **License:** `{l}`")?;
                }
            }
        }

        if !metadata.dependencies.is_empty() {
            writeln!(
                out,
                "- **Dependencies:** `{}`",
                metadata.dependencies.join("`, `")
            )?;
        }

        writeln!(out)?;
        Ok(())
    }

    fn render_file(&self, out: &mut dyn Write, path: &str, content: &str) -> Result<()> {
        writeln!(out, "\n## `{path}`\n\n```rust")?;
        out.write_all(content.as_bytes())?;
        writeln!(out, "\n```")?;
        Ok(())
    }

    fn render_crate_heading(&self, out: &mut dyn Write, name: &str) -> Result<()> {
        writeln!(out, "## Crate: {name}\n")?;
        Ok(())
    }

    fn render_workspace_heading(&self, out: &mut dyn Write, name: &str) -> Result<()> {
        writeln!(out, "# Workspace: {name}\n")?;
        Ok(())
    }

    fn render_structure_begin(&self, out: &mut dyn Write) -> Result<()> {
        writeln!(out, "## Project Structure\n")?;
        writeln!(out, "```")?;
        Ok(())
    }

    fn render_structure_end(&self, out: &mut dyn Write) -> Result<()> {
        writeln!(out, "```\n")?;
        Ok(())
    }

    fn render_structure_root(&self, out: &mut dyn Write, name: &str) -> Result<()> {
        writeln!(out, "{name}/")?;
        Ok(())
    }

    fn render_structure_member(&self, out: &mut dyn Write, path: &str) -> Result<()> {
        writeln!(out, "├── {path}/")?;
        Ok(())
    }

    fn tree_prefix(&self) -> &'static str {
        ""
    }
}
