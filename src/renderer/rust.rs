use crate::{
    SnapshotResult,
    renderer::{RenderStyle, Renderer},
};

use std::io::Write;

/// Renders output in Rust comment format
#[derive(Default)]
pub(crate) struct RustRenderer;

impl Renderer for RustRenderer {
    fn style(&self) -> RenderStyle {
        RenderStyle {
            line_prefix: "// ",
            metadata_key_prefix: "// ",
            // line count depends on content, so file_open takes content too
            file_open: |path, content| {
                let lines = content.lines().count();
                format!("\n// ----- {path} ({lines} lines) -----\n")
            },
            file_close: "",
            crate_heading: |name| format!("// ========== CRATE: {name} ==========\n"),
            workspace_heading: |name| format!("// ========== WORKSPACE: {name} ==========\n"),
            structure_begin: "// ========== PROJECT STRUCTURE ==========\n",
            structure_end: "",
            structure_root: |name| format!("// {name}/"),
            structure_member: |path| format!("// ├── {path}/"),
        }
    }

    fn render_header(&self, out: &mut dyn Write) -> SnapshotResult<()> {
        writeln!(out, "// ========================================")?;
        writeln!(out, "// CARGO SNAPSHOT")?;
        writeln!(out, "// Generated by cargo-snapshot")?;
        writeln!(out, "// ========================================\n")?;
        Ok(())
    }
}
